import sys, numpy as np, cv2, potrace
from PIL import Image
src, out = sys.argv[1], sys.argv[2]
im = np.array(Image.open(src).convert('RGBA')).astype(int)
H,W = im.shape[:2]
r,g,b,a = im[...,0],im[...,1],im[...,2],im[...,3]
alpha = a>128
black = alpha&(r<80)&(g<80)&(b<80)
white = alpha&(r>235)&(g>235)&(b>235)
pink = alpha&~black&~white
# background = transparent connected to border; silhouette = rest
trans = (~alpha).astype(np.uint8)
n,lab = cv2.connectedComponents(trans,connectivity=4)
border = (set(lab[0,:])|set(lab[-1,:])|set(lab[:,0])|set(lab[:,-1]))-{0}
sil = ~np.isin(lab,list(border))
sil = sil | alpha
# mouth component -> pink
n3,lab3,st3,_ = cv2.connectedComponentsWithStats(black.astype(np.uint8),connectivity=8)
mouth = np.zeros_like(black)
for i in range(1,n3):
  x,y,w,h,ar = st3[i]
  if 340<x<400 and 700<y<760: mouth |= lab3==i
black &= ~mouth; pink |= mouth
# eyes (white + ring) -> solid black blob
eyes = np.zeros((H,W),np.uint8)
for (c,ax,ang) in [((237.3,558.3),(178.0,284.8),14.5),((697.2,541.6),(180.5,282.9),167.1)]:
  cv2.ellipse(eyes,(int(c[0]),int(c[1])),(int(ax[0]/2+34),int(ax[1]/2+34)),ang,0,360,1,-1)
eyes = eyes>0
black |= eyes & sil; pink &= ~eyes
# overlap pink under black to avoid seams
pd = cv2.dilate(pink.astype(np.uint8),np.ones((7,7),np.uint8))>0
pink = pink | (pd & black)
def trace(mask, scale=2):
  small = cv2.resize(mask.astype(np.uint8)*255,(W//scale,H//scale),interpolation=cv2.INTER_AREA)>127
  bm = potrace.Bitmap(~small)
  pl = bm.trace(turdsize=20, alphamax=1.0, opticurve=True, opttolerance=0.3)
  data=[]; npts=0
  f=lambda p:(round(p.x*scale,1),round(p.y*scale,1))
  for curve in pl:
    sx,sy=f(curve.start_point); data+= [0,sx,sy]
    for seg in curve.segments:
      if seg.is_corner:
        data+=[1,*f(seg.c),1,*f(seg.end_point)]
      else:
        data+=[2,*f(seg.c1),*f(seg.c2),*f(seg.end_point)]
      npts+=1
    data+=[3]
  return data,len(pl),npts
layers={}
for name,mask in [('silhouette',sil),('fill',pink),('outline',black)]:
  d,nc,np_=trace(mask); layers[name]=d; print(name,'curves',nc,'segments',np_)
with open(out,'w') as fh:
  fh.write('// GENERATED by spike trace script from assets/images/mascot/mascot-happy.png.\n')
  fh.write('// Encoding: 0=moveTo(x,y) 1=lineTo(x,y) 2=cubicTo(x1,y1,x2,y2,x,y) 3=close.\n')
  fh.write('// Coordinates in source-image pixels (%d x %d).\n\n'%(W,H))
  fh.write('const double kBuddyWidth = %d;\nconst double kBuddyHeight = %d;\n\n'%(W,H))
  for k,v in layers.items():
    nm='kBuddy'+k[0].upper()+k[1:]
    fh.write('const List<double> %s = <double>[\n'%nm)
    s=', '.join(str(int(x)) if float(x).is_integer() else str(x) for x in v)
    # wrap
    import textwrap
    fh.write('\n'.join('  '+l for l in textwrap.wrap(s,96)))
    fh.write(',\n];\n\n')
